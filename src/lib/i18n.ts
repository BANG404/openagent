export const locale = writable<Locale>("zh");

// Reactive translation function for use in templates as {$t('key')}
export const t = derived(
  locale,
  ($locale) =>
    (key: TranslationKeys): string =>
      ($locale === "en" ? en : zh)[key],
);

// Non-reactive translation for use in script logic
export function tr(key: TranslationKeys): string {
  return (get(locale) === "en" ? en : zh)[key];
}

// Sync locale to Svelte store and notify the Rust plugin (fire-and-forget)
export function setLocale(newLocale: Locale): void {
  locale.set(newLocale);
  invoke("plugin:i18n|set_locale", { locale: newLocale }).catch(() => {});
}

// Read locale state from the Rust plugin and sync to the Svelte store
export async function initLocale(): Promise<void> {
  try {
    const stored = await invoke<string>("plugin:i18n|get_locale");
    if (stored === "zh" || stored === "en") locale.set(stored);
  } catch {}
}

// Listen for locale changes emitted by the Rust plugin
export function listenLocale(): Promise<() => void> {
  return listen<string>("i18n:locale-changed", (e) => {
    const l = e.payload;
    if (l === "zh" || l === "en") locale.set(l);
  });
}

/**
 * Called once at startup. Priority: savedLanguage > system locale > 'zh'.
 * Also sets up the Rust-side locale change listener.
 */
export async function initI18n(savedLanguage?: string | null): Promise<void> {
  let target: Locale;

  if (savedLanguage === "zh" || savedLanguage === "en") {
    target = savedLanguage;
  } else {
    try {
      const sysLocale = await invoke<string>("get_system_locale");
      target = sysLocale.toLowerCase().startsWith("zh") ? "zh" : "en";
    } catch {
      target = "zh";
    }
  }

  locale.set(target);
  invoke("plugin:i18n|set_locale", { locale: target }).catch(() => {});
  listenLocale().catch(() => {});
}
